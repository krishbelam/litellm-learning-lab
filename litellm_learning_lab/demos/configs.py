"""This file handles the configurations required by the modules
"""
import os
from dotenv import load_dotenv

load_dotenv()


class Settngs:
    BASE_URL = os.getenv("LITELLM_BASE_URL", "http://localhost:4000/v1")
    VIRTUAL_KEY = os.getenv("LITELLM_VIRTUAL_KEY")
    MODEL = os.getenv("LITELLM_MODEL", "local-llama-small-ctx")
    BOOKSTORE_BASIC_KEY = os.environ["BOOKSTORE_BASIC_KEY"]
    BOOKSTORE_PRO_KEY = os.environ["BOOKSTORE_PRO_KEY"]

    REQUEST_COUNT = int(os.getenv("REQUEST_COUNT", "8"))
    MAX_WORKERS = int(os.getenv("MAX_WORKERS", "8"))


if not Settngs.VIRTUAL_KEY:
    raise SystemExit(
        "Set LITELLM_VIRTUAL_KEY to a virtual key generated by your LiteLLM Proxy."
    )
